#!/usr/bin/env python3
"""pacman_font.py - the font of the Pac-Man arcade as C64 characters, for the
loader (pacman_loader.s).

    python3 pacman_font.py pacman.zip gen/pacfont.inc

The glyphs of the tiles of pacman.5e (2 bpp: every colour but 0 is a pixel)
at the screen codes of the C64, so that the texts are written with scrcode:
the letters ($01-$1A from the tiles $41-$5A), the digits ($30-$39 from the
tiles $30-$39, on the line of the letters; $00-$09 are one row lower), "-"
and "." ($2D, $2E from $3B, $25).  The arcade has no "%": one is drawn here
in its style; $A0 is a segment of the progress bar.

The output, for ca65: FONT_GLYPHS, then "screen code, 8 bytes" per glyph.
"""

import sys
import zipfile
from pacman_gfx import decode, rot90, TILE_X, TILE_Y

PERCENT = ['.##...#.',
           '.##..##.',
           '....##..',
           '...##...',
           '..##....',
           '.##..##.',
           '.#...##.',
           '........']
SEGMENT = ['#######.'] * 7 + ['........']


def rows(tile):
    return [sum(1 << (7 - x) for x in range(8) if tile[y][x]) for y in range(8)]


def art(lines):
    return [sum(1 << (7 - x) for x, c in enumerate(l) if c == '#') for l in lines]


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: pacman_font.py pacman.zip OUT.inc')
    z = zipfile.ZipFile(sys.argv[1])
    tiles = [rot90(decode(z.read('pacman.5e'), 16 * i, 8, TILE_X, TILE_Y)) for i in range(256)]
    glyphs = [(0x01 + i, rows(tiles[0x41 + i])) for i in range(26)]
    glyphs += [(0x30 + i, rows(tiles[0x30 + i])) for i in range(10)]
    glyphs += [(0x2D, rows(tiles[0x3B])), (0x2E, rows(tiles[0x25])),
               (0x25, art(PERCENT)), (0xA0, art(SEGMENT))]
    with open(sys.argv[2], 'w') as s:
        s.write('; pacfont.inc - generated by pacman_font.py from the Pac-Man arcade ROMs: do not edit.\n'
                '; screen code, 8 bytes of the glyph\n\n'
                'FONT_GLYPHS = %d\n\n' % len(glyphs))
        for code, b in glyphs:
            s.write('        .byte   $%02x, %s\n' % (code, ','.join('$%02x' % v for v in b)))


if __name__ == '__main__':
    main()
